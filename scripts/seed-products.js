async function run() {
  const conn = await mysql.createConnection({
    host:     process.env.DB_HOST     || 'localhost',
    port:     parseInt(process.env.DB_PORT) || 3306,
    user:     process.env.DB_USER     || 'root',
    password: process.env.DB_PASS     || '',
    database: 'mathstudy',
  });

  // Build category slug → id map
  const [catRows] = await conn.query('SELECT id, slug FROM categories');
  const catMap = {};
  for (const row of catRows) catMap[row.slug] = row.id;

  let inserted = 0;
  let skipped  = 0;

  for (const p of PRODUCTS) {
    const catId = catMap[CAT[p.cat]];
    if (!catId) {
      console.warn(`  WARNING: category not found for slug "${p.cat}" — skipping "${p.title}"`);
      skipped++;
      continue;
    }

    const [result] = await conn.query(`
      INSERT IGNORE INTO products
        (title, slug, description, short_desc, category_id, price, original_price,
         cover_image, pdf_file, page_count, grade, board,
         is_published, is_featured, meta_title, meta_desc)
      VALUES (?,?,?,?,?,?,?,?,?,?,?,?,1,?,?,?)
    `, [
      p.title, p.slug, p.description, p.short_desc, catId,
      p.price, p.original_price, p.cover_image, p.pdf_file,
      p.page_count, p.grade, p.board,
      p.is_featured, p.meta_title, p.meta_desc,
    ]);

    if (result.affectedRows > 0) {
      console.log(`  ✓  ${p.title}`);
      inserted++;
    } else {
      console.log(`  –  already exists: ${p.slug}`);
      skipped++;
    }
  }

  await conn.end();
  console.log(`\nDone. Inserted: ${inserted}, Skipped/already existed: ${skipped}`);
}

run().catch(e => { console.error(e); process.exit(1); });
